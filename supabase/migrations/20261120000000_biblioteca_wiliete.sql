create table if not exists public.courses (
  id bigint generated by default as identity primary key,
  name text not null unique,
  count integer not null default 0,
  icon text not null default '',
  created_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.works (
  id bigint generated by default as identity primary key,
  title text not null unique,
  author text not null,
  course text not null,
  year integer not null,
  advisor text not null,
  views integer not null default 0,
  pages integer not null default 0,
  color text not null default '#087B48',
  abstract text not null,
  keywords text[] not null default '{}',
  contact boolean not null default true,
  file_url text,
  created_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  role text not null default 'reader' check (role in ('reader', 'finalist', 'admin')),
  created_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.favorites (
  user_id uuid not null references auth.users(id) on delete cascade,
  work_id bigint not null references public.works(id) on delete cascade,
  created_at timestamptz not null default timezone('utc', now()),
  primary key (user_id, work_id)
);

create table if not exists public.submissions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  author text not null,
  course text not null,
  year integer not null,
  advisor text,
  abstract text,
  file_url text,
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  created_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.chat_messages (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references auth.users(id) on delete cascade,
  recipient_id uuid not null references auth.users(id) on delete cascade,
  content text not null check (char_length(content) between 1 and 2000),
  read_at timestamptz,
  created_at timestamptz not null default timezone('utc', now()),
  check (sender_id <> recipient_id)
);

create index if not exists chat_messages_sender_recipient_created_idx
  on public.chat_messages (sender_id, recipient_id, created_at desc);

do $$
begin
  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'chat_messages'
  ) then
    alter publication supabase_realtime add table public.chat_messages;
  end if;
end;
$$;

insert into storage.buckets (id, name, public)
values ('work-files', 'work-files', false)
on conflict (id) do nothing;

