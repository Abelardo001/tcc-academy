alter table public.submissions enable row level security;
alter table public.chat_messages enable row level security;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin'
  );
$$;

create policy "Public can read courses"
  on public.courses for select
  using (true);

create policy "Public can read works"
  on public.works for select
  using (true);

create policy "Admins can manage courses"
  on public.courses for all
  using (public.is_admin())
  with check (public.is_admin());

create policy "Admins can manage works"
  on public.works for all
  using (public.is_admin())
  with check (public.is_admin());

create policy "Users can read their profile"
  on public.profiles for select
  using (auth.uid() = id);

create policy "Users can update their profile"
  on public.profiles for update
  using (auth.uid() = id)
  with check (auth.uid() = id);

create or replace function public.prevent_profile_role_escalation()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  if new.role = 'admin' and not public.is_admin() then
    new.role := 'reader';
  elsif new.role not in ('reader', 'finalist') then
    new.role := 'reader';
  end if;
  return new;
end;
$$;

drop trigger if exists protect_profile_role on public.profiles;
create trigger protect_profile_role
  before insert or update on public.profiles
  for each row execute function public.prevent_profile_role_escalation();

create policy "Admins can read profiles"
